class Event:
    """A dashboard-facing change notification. Topic examples: device.updated, job.updated."""

    __slots__ = ("data", "topic")

    def __init__(self, topic: str, data: dict[str, Any]) -> None:
        self.topic = topic
        self.data = data


class EventPublisher(Protocol):
    def publish(self, event: Event) -> None: ...


class AgentGateway(Protocol):
    """How use cases reach connected agents without knowing about websockets."""

    def wake(self, host_id: UUID) -> None:
        """Tell the gateway there may be work to dispatch to this host."""
        ...

    def cancel(self, host_id: UUID, execution_id: UUID, reason: str) -> None: ...


class AlertNotifier(Protocol):
    async def notify(self, alert: AlertRecord, webhooks: list[WebhookRecord]) -> None: ...
